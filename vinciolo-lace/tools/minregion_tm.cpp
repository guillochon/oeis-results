// T(n,k): number of n x n 0/1 arrays invariant under the 8 symmetries of the square in which every
// 8-connected region of 1s has at least k cells.  (k = 2: no lone 1 = b_pinhole_d4.txt.)
//
// Method: frontier transfer matrix over the octant cells (i <= j <= h-1, i = row, j = column, both counted from
// the outer edge of the top-left quarter).  Each octant cell stands for its orbit of s = 1, 4 or 8 cells.
// Two octant cells are joined when some images are king-adjacent.  A region X of the full array that meets the
// octant contains every octant cell of its quotient component C, and its stabilizer H is generated by the
// reflections in the two octant walls (diagonal D, vertical midline V) that C touches; a cell touches a wall
// when its mirror image is itself or a king neighbor.  So |X| = (sum of s over C) * |H| / 8 with
// |H| = 1, 2, 2, 8 for no wall, D only, V only, both.  State per frontier cell: component label (0 = cell is 0);
// per component: S = sum of s (capped once the region is surely >= k) and the two wall flags.
//
// Usage: minregion_tm n k [modbits]   prints "n k T(n,k)".  Counts are exact in unsigned __int128 while the
// octant has <= 127 cells (n <= 30); beyond that pass a modulus id (0..4) to get T mod p (see crt.py primes).
#include <bits/stdc++.h>
using namespace std;
typedef unsigned __int128 u128;
typedef unsigned long long u64;

static string str128(u128 x) { if (!x) return "0"; string s; while (x) { s += char('0' + int(x % 10)); x /= 10; } reverse(s.begin(), s.end()); return s; }

int n, K, h, NV;
vector<int> orb_s, flagD, flagV, lastNb;
vector<vector<int>> nbBefore;   // neighbors of vertex t with smaller index
int modid = -1; u64 MODP[5] = {0, 4611686018427387847ULL, 4611686018427387817ULL, 4611686018427387787ULL, 4611686018427387761ULL};
// modid 0: mod 2^64 (wraparound); 1..4: the primes 2^62-57, -87, -117, -143.

static inline int Hsize(int f) { return f == 0 ? 1 : (f == 3 ? 8 : 2); }
static inline int capFor(int f) { int hs = Hsize(f); return (8 * K + hs - 1) / hs; }

struct Hasher { size_t operator()(const string &s) const { u64 x = 1469598103934665603ULL; for (unsigned char c : s) { x ^= c; x *= 1099511628211ULL; } return x ^ (x >> 29); } };

int main(int argc, char **argv) {
    n = atoi(argv[1]); K = atoi(argv[2]); if (argc > 3) modid = atoi(argv[3]);
    h = (n + 1) / 2;
    // octant vertices in processing order: column j major, row i minor
    map<pair<int,int>, int> id; vector<pair<int,int>> cell;
    for (int j = 0; j < h; j++) for (int i = 0; i <= j; i++) { id[{i, j}] = cell.size(); cell.push_back({i, j}); }
    NV = cell.size();
    auto rep = [&](int r, int c) { int a = min(r, n - 1 - r), b = min(c, n - 1 - c); return id[{min(a, b), max(a, b)}]; };
    orb_s.assign(NV, 0); flagD.assign(NV, 0); flagV.assign(NV, 0);
    for (int r = 0; r < n; r++) for (int c = 0; c < n; c++) orb_s[rep(r, c)]++;
    vector<set<int>> adj(NV);
    auto near = [&](int r1, int c1, int r2, int c2) { return abs(r1 - r2) <= 1 && abs(c1 - c2) <= 1; };
    for (int v = 0; v < NV; v++) {
        int r = cell[v].first, c = cell[v].second;          // canonical position in the top-left quarter
        flagD[v] = near(r, c, c, r);
        flagV[v] = near(r, c, r, n - 1 - c);
        for (int a = -1; a <= 1; a++) for (int b = -1; b <= 1; b++) {
            if (!a && !b) continue; int x = r + a, y = c + b;
            if (x < 0 || y < 0 || x >= n || y >= n) continue;
            int w = rep(x, y); if (w != v) { adj[v].insert(w); adj[w].insert(v); }
        }
    }
    lastNb.assign(NV, 0); nbBefore.assign(NV, {});
    for (int v = 0; v < NV; v++) { lastNb[v] = v; for (int w : adj[v]) { lastNb[v] = max(lastNb[v], w); if (w < v) nbBefore[v].push_back(w); } }

    // state: frontier vertex list is the same for all states at a given step
    vector<int> front;
    unordered_map<string, u128, Hasher> cur, nxt;
    cur[string()] = 1;
    size_t peak = 0;
    for (int t = 0; t < NV; t++) {
        // positions of t's earlier neighbors in the frontier
        vector<int> pos; for (int w : nbBefore[t]) { int p = find(front.begin(), front.end(), w) - front.begin(); if (p == (int)front.size()) { fprintf(stderr, "frontier bug\n"); return 1; } pos.push_back(p); }
        vector<int> nf = front; nf.push_back(t);
        vector<int> keep; for (int p = 0; p < (int)nf.size(); p++) if (lastNb[nf[p]] > t) keep.push_back(p);
        int F = front.size();
        nxt.clear(); nxt.reserve(cur.size() * 2);
        for (auto &kv : cur) {
            const string &s = kv.first;
            // decode
            int lab[64]; int nc = 0; int S[64], fl[64];
            for (int p = 0; p < F; p++) { lab[p] = (unsigned char)s[p]; nc = max(nc, lab[p]); }
            for (int c = 1; c <= nc; c++) { int o = F + 3 * (c - 1); S[c] = (unsigned char)s[o] | ((unsigned char)s[o + 1] << 8); fl[c] = (unsigned char)s[o + 2]; }
            for (int x = 0; x <= 1; x++) {
                int L[64], SS[64], FF[64]; int ncc = nc;
                for (int p = 0; p < F; p++) L[p] = lab[p];
                for (int c = 1; c <= nc; c++) { SS[c] = S[c]; FF[c] = fl[c]; }
                if (x == 0) L[F] = 0;
                else {
                    int nw = ++ncc; SS[nw] = orb_s[t]; FF[nw] = flagD[t] | (flagV[t] << 1);
                    bool merged[64] = {false};
                    for (int p : pos) { int c = L[p]; if (c && c != nw && !merged[c]) { merged[c] = true; SS[nw] += SS[c]; FF[nw] |= FF[c]; } }
                    for (int p = 0; p < F; p++) if (L[p] && merged[L[p]]) L[p] = nw;
                    L[F] = nw;
                    SS[nw] = min(SS[nw], capFor(FF[nw]));
                }
                // drop leaving vertices, check closed regions
                bool ok = true;
                vector<char> alive(ncc + 1, 0);
                for (int p : keep) if (L[p]) alive[L[p]] = 1;
                for (int p = 0; p <= F && ok; p++) {
                    int c = L[p]; if (!c || alive[c]) continue;
                    // component c closes (only check once: mark alive to skip duplicates)
                    if ((long)SS[c] * Hsize(FF[c]) < 8L * K) ok = false;
                    alive[c] = 2;
                }
                if (!ok) continue;
                // canonical relabel
                string ns; ns.reserve(keep.size() + 3 * keep.size());
                int mp[64]; memset(mp, 0, sizeof mp); int m = 0; vector<int> order;
                for (int p : keep) { int c = L[p]; if (c && !mp[c]) { mp[c] = ++m; order.push_back(c); } ns.push_back(char(c ? mp[c] : 0)); }
                for (int c : order) { int v = min(SS[c], capFor(FF[c])); ns.push_back(char(v & 255)); ns.push_back(char(v >> 8)); ns.push_back(char(FF[c])); }
                u128 add = kv.second;
                auto it = nxt.find(ns);
                if (it == nxt.end()) nxt.emplace(move(ns), add);
                else {
                    if (modid <= 0) it->second += add;   // exact (or mod 2^128 / 2^64 below)
                    else { it->second += add; if (it->second >= MODP[modid]) it->second -= MODP[modid]; }
                }
            }
        }
        swap(cur, nxt);
        if (modid == 0) for (auto &kv : cur) kv.second = (u64)kv.second;
        vector<int> f2; for (int p : keep) f2.push_back(nf[p]); front = f2;
        peak = max(peak, cur.size());
    }
    u128 tot = 0; for (auto &kv : cur) { tot += kv.second; if (modid > 0) tot %= MODP[modid]; }
    if (modid == 0) tot = (u64)tot;
    printf("%d %d %s\n", n, K, str128(tot).c_str());
    fprintf(stderr, "n=%d k=%d octant=%d peak_states=%zu\n", n, K, NV, peak);
    if (modid < 0 && NV > 127) fprintf(stderr, "WARNING: octant > 127 cells, exact count may overflow\n");
    return 0;
}
